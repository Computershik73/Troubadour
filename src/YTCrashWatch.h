#import <Foundation/Foundation.h>

/**
 * Следы прошлого обрыва и ловушки для следующего — только в отладочной сборке.
 *
 * Журнал пишется отложенно, а падение не оставляет в нём ничего: в двух
 * журналах подряд с iPad (30.10.2026) последней строкой стояло обычное
 * «Здоровье» посреди ролика, и отличить своё падение от снятия системой
 * было не по чему. Теперь:
 *
 * - исключение и сигнал (SIGSEGV, SIGBUS, SIGABRT…) пишутся в журнал
 *   сразу, со стеком вызовов, прямо из обработчика;
 * - при запуске видно, чем кончился прошлый: на экране или в фоне,
 *   с записью о падении или без неё;
 * - свежие отчёты системы о снятии по памяти и о падениях (папка
 *   CrashReporter) переписываются в журнал. Из пакета приложение живёт
 *   без песочницы, и папка ему видна; из IPA — нет, тогда молчим.
 */

/** Первым делом при запуске: разбор прошлого обрыва и ловушки. */
void YTCrashWatchStart(void);

/** На экране мы или в фоне — для разбора при следующем запуске. */
void YTCrashWatchForeground(BOOL foreground);

/** Обычное завершение: следующий запуск не должен считать его обрывом. */
void YTCrashWatchClean(void);

/**
 * Ставим обновление: `dpkg` заменит бинарник, и приложение закроют.
 * Без этой отметки следующий запуск принял бы это за снятие на экране
 * (журнал 31.10.2026, iPad 1: обновление до 1.6-25 записано обрывом).
 */
void YTCrashWatchUpdating(void);
