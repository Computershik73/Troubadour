#import <Foundation/Foundation.h>

/**
 * Приводит строку к тому виду, который система в силах нарисовать.
 *
 * Две беды приходят с сервера, и обе кончаются падением внутри CoreText,
 * не оставляя в отчёте ни одной нашей строки:
 *
 * 1. Оборванная суррогатная пара. YouTube режет длинные названия по своей
 *    мерке, не глядя на пары, и у названия со значком в месте обрыва
 *    приезжает половина знака. Такая строка — уже не UTF-16.
 *
 * 2. Знак, которого в этой системе нет вовсе. Значки прибывают в Unicode
 *    каждый год, а iOS 5–7 старше их на десятилетие: 🤯 появился на восемь
 *    лет позже iOS 7. Нарисовать его нечем, и попытка подобрать замену
 *    роняет систему — так и падала страница «Вы».
 *
 * Первое чинится подстановкой «плейсхолдера», второе — выбрасыванием
 * знака: показать его всё равно нечем.
 *
 * Зовётся у самого входа — при разборе ответа сервера, — поэтому дальше
 * по приложению ходит уже безопасный текст: и в подписях, и в заголовках
 * кнопок, и в системных листах, куда наш присмотр за подписями не достаёт.
 * Обычный текст — буквы, цифры, знаки препинания — распознаётся первым же
 * перебором и возвращается как есть.
 */
NSString *YTSafeText(NSString *text);
